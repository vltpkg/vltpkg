#!/usr/bin/env node
/**
 * Generates src/cli-sdk/src/commands-map.ts — the S2 fallback.
 *
 * `import()` below module top level is silently dropped (F4) and a
 * template-literal specifier fails `check --check-deps` outright (S2), so
 * command dispatch cannot be lazy in the compiled binary. This emits the
 * static table `loadCommand` reads.
 *
 *   node scripts/perry/gen/commands-map.mjs           regenerate
 *   node scripts/perry/gen/commands-map.mjs --check   fail if stale (CI)
 *
 * Source of truth is the `commands` map in config/definition.ts, so a new
 * command is picked up by re-running this, not by editing the output.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, resolve, join } from 'node:path'

const ROOT = resolve(dirname(new URL(import.meta.url).pathname), '../../..')
const DEF = join(ROOT, 'src/cli-sdk/src/config/definition.ts')
const OUT = join(ROOT, 'src/cli-sdk/src/commands-map.ts')

// canonical module names = the values of `commands` (canonical + aliases),
// which are exactly the files under commands/
const src = readFileSync(DEF, 'utf8')
const block = (name) => {
  const i = src.indexOf(`const ${name} = {`)
  if (i === -1) throw new Error(`no ${name} in definition.ts`)
  return src.slice(i, src.indexOf('} as const', i))
}
const pairs = s =>
  [...s.matchAll(/^\s*'?([\w?-]+)'?:\s*'([\w-]+)',/gm)].map(m => [m[1], m[2]])
const commands = Object.fromEntries([
  ...pairs(block('canonicalCommands')),
  ...pairs(block('aliases')),
])
const modules = [...new Set(Object.values(commands))].sort()
for (const m of modules)
  if (!existsSync(join(ROOT, `src/cli-sdk/src/commands/${m}.ts`)))
    throw new Error(`commands/${m}.ts missing (from definition.ts)`)

const ident = m => m.replace(/-(\w)/g, (_, c) => c.toUpperCase())
const text = `/* GENERATED by scripts/perry/gen/commands-map.mjs — do not edit.
 *
 * Static command dispatch. \`import()\` below module top level is silently
 * dropped by the compiler (perry-notes F4) and a template-literal specifier
 * fails \`check --check-deps\` (S2), so the compiled binary cannot load
 * commands lazily. Every command's dep closure therefore links into the
 * binary whether or not it runs.
 *
 * Regenerate after adding a command: node scripts/perry/gen/commands-map.mjs
 */
${modules.map(m => `import * as ${ident(m)} from './commands/${m}.ts'`).join('\n')}

import type { Command } from './load-command.ts'
import type { Commands } from './config/definition.ts'

export const commandModules = {
${modules.map(m => `  '${m}': ${ident(m)},`).join('\n')}
} as unknown as Record<Commands[keyof Commands], Command<unknown>>
`

if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) {
    console.error('src/cli-sdk/src/commands-map.ts is stale — re-run scripts/perry/gen/commands-map.mjs')
    process.exit(1)
  }
  console.log(`commands-map.ts up to date (${modules.length} commands)`)
} else {
  writeFileSync(OUT, text)
  console.log(`wrote src/cli-sdk/src/commands-map.ts (${modules.length} commands)`)
}
