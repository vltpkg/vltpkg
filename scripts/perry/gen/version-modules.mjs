#!/usr/bin/env node
/**
 * Generates `src/<pkg>/src/version.ts` for every package that reads its own
 * version at runtime.
 *
 * Those reads go through `loadPackageJson(import.meta.filename, …)` plus an
 * esbuild `process.env.__VLT_INTERNAL_*_PACKAGE_JSON` define. Neither
 * survives compilation: `import.meta.filename` keeps the build machine's
 * source path (perry-notes F12), no package.json ships beside the binary,
 * and there is no define mechanism. So the version is compiled in as a
 * literal and the runtime lookup is kept for the Node builds, where a
 * published package's own package.json stays authoritative.
 *
 *   node scripts/perry/gen/version-modules.mjs           regenerate
 *   node scripts/perry/gen/version-modules.mjs --check   fail if stale (CI)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, resolve, join } from 'node:path'

const ROOT = resolve(dirname(new URL(import.meta.url).pathname), '../../..')

// pkg dir -> the esbuild define its Node build injects
const TARGETS = {
  'src/cli-sdk': '__VLT_INTERNAL_CLI_PACKAGE_JSON',
  'src/registry-client': '__VLT_INTERNAL_REGISTRY_CLIENT_PACKAGE_JSON',
  'src/security-archive': '__VLT_INTERNAL_CLI_PACKAGE_JSON',
}

const render = (pkgVersion, define) => `/* GENERATED by scripts/perry/gen/version-modules.mjs — do not edit.
 *
 * The runtime version lookup does not survive compilation:
 * \`import.meta.filename\` keeps the build machine's source path
 * (perry-notes F12), no package.json ships beside the binary, and there is
 * no esbuild \`define\` in that build. So the compiled build reads the
 * literal below and the Node builds keep the lookup, which stays
 * authoritative for a published package.
 *
 * Regenerate after a version bump: node scripts/perry/gen/version-modules.mjs
 */
import { loadPackageJson } from 'package-json-from-dist'

const compiled = '${pkgVersion}'

export const version: string =
  'perry' in process.versions ? compiled : (
    (
      loadPackageJson(
        import.meta.filename,
        process.env.${define},
      ) as { version: string }
    ).version
  )
`

let stale = 0
for (const [dir, define] of Object.entries(TARGETS)) {
  const pj = JSON.parse(readFileSync(join(ROOT, dir, 'package.json'), 'utf8'))
  const out = join(ROOT, dir, 'src/version.ts')
  const text = render(pj.version, define)
  if (process.argv.includes('--check')) {
    if (!existsSync(out) || readFileSync(out, 'utf8') !== text) {
      console.error(`${dir}/src/version.ts is stale — re-run scripts/perry/gen/version-modules.mjs`)
      stale++
    }
  } else {
    writeFileSync(out, text)
    console.log(`wrote ${dir}/src/version.ts (${pj.version})`)
  }
}
if (stale) process.exit(1)
if (process.argv.includes('--check')) console.log('version modules up to date')
